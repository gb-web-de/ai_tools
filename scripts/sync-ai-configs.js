#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const rulesDir = path.join(rootDir, 'ai-rules');

console.log('🔄 Syncing AI Configurations from ai-rules/ ...');

if (!fs.existsSync(rulesDir)) {
  console.error(`❌ Rules directory ${rulesDir} does not exist!`);
  process.exit(1);
}

const ruleFiles = fs.readdirSync(rulesDir).filter(f => f.endsWith('.md')).sort();
const combinedRules = ruleFiles.map(file => {
  const content = fs.readFileSync(path.join(rulesDir, file), 'utf8');
  return `<!-- MODULE: ${file} -->\n${content.trim()}`;
}).join('\n\n---\n\n');

const headerNotice = `<!--
===================================================================
DO NOT EDIT DIRECTLY.
Auto-generated by scripts/sync-ai-configs.js from ai-rules/
Run 'npm run sync-ai' to regenerate.
===================================================================
-->\n\n`;

// 1. Generate AGENTS.md (Universal Standard)
const agentsContent = `${headerNotice}# TYPO3 AI Master Agent Directives

You are an expert TYPO3 Core and Extension developer working with TYPO3 v12, v13, and v14.
You strictly enforce security hardening, modern PHP 8.2+ practices, and official TYPO3 architectural patterns.

## Non-Negotiable Rules
1. **Strict Types**: EVERY PHP file must start with \`declare(strict_types=1);\`.
2. **PHP 8.2+**: Use Constructor Promotion, readonly properties/classes, and PHP 8 Attributes.
3. **No Raw SQL**: NEVER concatenate raw variables into queries. Always use \`ConnectionPool\` and \`QueryBuilder\` with named parameters.
4. **No XSS in Fluid**: Never use \`f:format.raw()\` or \`escapeOutput="false"\` on untrusted user input.
5. **Access Control**: Never use \`@ignorevalidation\` or \`#[IgnoreValidation]\` on mutating Controller actions without manual verification.
6. **No Deprecations**: NEVER use legacy hooks if a PSR-14 event exists; never use \`$GLOBALS['TYPO3_DB']\` or direct \`$GLOBALS['TSFE']\` calls.
7. **Symfony DI**: Always manage dependencies via Constructor Injection.

---

## Detailed Guidelines & Coding Standards

${combinedRules}
`;

fs.writeFileSync(path.join(rootDir, 'AGENTS.md'), agentsContent, 'utf8');
console.log('✅ Generated AGENTS.md');

// 2. Generate CLAUDE.md (Anthropic Claude Code / Desktop)
const claudeContent = `${headerNotice}# Claude Code Instructions - TYPO3 CMS Guidelines

Target: TYPO3 v12 / v13 / v14
PHP: PHP 8.2+ with \`declare(strict_types=1);\`

## Key Development Rules
- Use QueryBuilder with \`$queryBuilder->createNamedParameter()\` for all SQL operations.
- Do not disable Fluid template escaping.
- Implement Dependency Injection in \`Configuration/Services.yaml\` with Constructor Promotion.
- Use PSR-14 Events (\`#[AsEventListener]\`) instead of legacy hooks.
- For CLI tasks, use Symfony Console Commands with \`#[AsCommand]\`.
- For automated security audits, utilize the MCP tools: \`audit_typo3_instance\`, \`analyze_typo3_extension\`, \`run_phpstan_security_audit\`, and \`fix_fluid_xss\`.

---

${combinedRules}
`;
fs.writeFileSync(path.join(rootDir, 'CLAUDE.md'), claudeContent, 'utf8');
console.log('✅ Generated CLAUDE.md');

// 3. Generate .cursorrules
fs.writeFileSync(path.join(rootDir, '.cursorrules'), agentsContent, 'utf8');
console.log('✅ Generated .cursorrules');

// 4. Generate .cursor/rules/typo3-rules.mdc
const cursorRulesDir = path.join(rootDir, '.cursor', 'rules');
fs.mkdirSync(cursorRulesDir, { recursive: true });

const cursorMdcContent = `---
description: Official TYPO3 v12/v13/v14 Coding & Security Guidelines
globs: **/*.php, **/*.html, **/*.yaml, **/*.typoscript
alwaysApply: true
---

${agentsContent}
`;
fs.writeFileSync(path.join(cursorRulesDir, 'typo3-rules.mdc'), cursorMdcContent, 'utf8');
console.log('✅ Generated .cursor/rules/typo3-rules.mdc');

// 5. Generate .windsurfrules
fs.writeFileSync(path.join(rootDir, '.windsurfrules'), agentsContent, 'utf8');
console.log('✅ Generated .windsurfrules');

// 6. Generate .github/copilot-instructions.md
const githubDir = path.join(rootDir, '.github');
fs.mkdirSync(githubDir, { recursive: true });
fs.writeFileSync(path.join(githubDir, 'copilot-instructions.md'), agentsContent, 'utf8');
console.log('✅ Generated .github/copilot-instructions.md');

// 7. Generate Editor MCP Configurations (.cursor/mcp.json and .vscode/mcp.json)
const mcpServerPath = path.join(rootDir, 'typo3-mcp-server', 'build', 'index.js');
const mcpConfig = {
  mcpServers: {
    "typo3-security": {
      command: "node",
      args: [mcpServerPath]
    }
  }
};

fs.writeFileSync(path.join(rootDir, '.cursor', 'mcp.json'), JSON.stringify(mcpConfig, null, 2), 'utf8');
console.log('✅ Generated .cursor/mcp.json');

const vscodeDir = path.join(rootDir, '.vscode');
fs.mkdirSync(vscodeDir, { recursive: true });
fs.writeFileSync(path.join(vscodeDir, 'mcp.json'), JSON.stringify(mcpConfig, null, 2), 'utf8');
console.log('✅ Generated .vscode/mcp.json');

console.log('\n✨ All AI configurations successfully synchronized!');
